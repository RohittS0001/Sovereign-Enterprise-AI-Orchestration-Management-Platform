"""Connect every platform from one file, and see what is connected.

python -m scripts.connections --init       # create connections.env: one place for every link/key
python -m scripts.connections              # checklist: what you have added, what is missing
python -m scripts.connections --check      # also call each configured service (network!)
python -m scripts.connections --markdown   # regenerate docs/integrations.md and the template
"""

import argparse
import asyncio
import sys
from pathlib import Path

from backend.app.core.config import Settings
from backend.app.integrations.connectors.registry import ALL_SPECS
from backend.app.integrations.connectors.spec import CATEGORY_TITLES, ConnectorSpec

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "integrations.md"
TEMPLATE = ROOT / "connections.env.example"
CONNECTIONS = ROOT / "connections.env"


def _default(field: str) -> str:
    """The value written into the template: the setting's default, empty for secrets."""
    import json

    from pydantic import SecretStr

    from backend.app.core.config import PROJECT_ROOT

    info = Settings.model_fields[field]
    value = info.get_default(call_default_factory=True)
    if value is None or isinstance(value, SecretStr) or value == "":
        return ""
    if isinstance(value, Path):  # project-relative and with / so the template is portable
        try:
            return value.relative_to(PROJECT_ROOT).as_posix()
        except ValueError:
            return value.as_posix()
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list | dict):
        return json.dumps(value)
    return str(value)


def _hint(field: str, required: bool) -> str:
    """The comment after a variable: required, its default, or the expected format."""
    annotation = str(Settings.model_fields[field].annotation)
    parts = ["required"] if required else []
    default = _default(field)
    if "list" in annotation:
        parts.append('list, e.g. ["value1","value2"]')
    if default and default != "[]":
        parts.append(f"default: {default}")
    return f"    # {' · '.join(parts)}" if parts else ""


def env_template() -> str:
    """connections.env.example: every integration's variables, grouped, with where to find them.

    Every value starts empty, and empty lines are ignored when settings load, so the file never
    changes anything until a value is pasted in (it also never blanks out a value in .env).
    """
    lines = [
        "# ======================================================================================",
        "# connections.env: paste the links and keys of the platforms you use, in one place.",
        "# Generated by `python -m scripts.connections --markdown`; copy it with",
        "# `python -m scripts.connections --init` (creates connections.env, never committed).",
        "#",
        "# - Paste a value after the = sign. Lines left empty are ignored, so you can fill in",
        "#   platforms one at a time; nothing here overrides .env until it has a value.",
        "# - Fill in all REQUIRED lines of a platform to switch it on; the rest is optional.",
        "# - Restart the API, then run `python -m scripts.connections` (or open Integrations in",
        "#   the app) to see what is connected and what is still missing.",
        "# ======================================================================================",
        "",
        "# Set to false to use the real platforms below (true = synthetic demo data everywhere).",
        "DEMO_MODE=",
        "",
    ]
    seen: set[str] = set()
    for category, title in CATEGORY_TITLES.items():
        specs = [s for s in ALL_SPECS if s.category == category]
        if not specs:
            continue
        lines += [f"# {'=' * 86}", f"# {title.upper()}", f"# {'=' * 86}", ""]
        for spec in specs:
            lines.append(f"# --- {spec.title} ---")
            if spec.setup:
                lines.append(f"# Where to get it: {spec.setup}")
            if spec.docs_url:
                lines.append(f"# Docs: {spec.docs_url}")
            for field in (*spec.required, *spec.optional):
                required = field in spec.required
                if field in seen:
                    if required:
                        lines.append(f"# {field.upper()} is shared: fill it in above")
                    continue
                seen.add(field)
                lines.append(f"{field.upper()}={_hint(field, required)}")
            lines.append("")
    lines += [
        f"# {'=' * 86}",
        "# PER-PROJECT LINKS (not set here)",
        f"# {'=' * 86}",
        "# Which records belong to which project is part of each project's configuration",
        "# (PUT /api/v1/projects/<KEY>, field `links`), for example:",
        '#   "slack_channels": ["C0123ABCD"]        Slack channels indexed for the project',
        '#   "cloud_tag_values": ["PHX"]            AWS/Azure/GCP tag value (default: the key)',
        '#   "pagerduty_services": ["P123ABC"]      "datadog_services": ["payments-api"]',
        '#   "servicenow_services": ["Payments API"] "zendesk_tags": ["phx"]',
        '#   "sentry_projects", "jenkins_jobs", "argocd_apps", "sonarqube_projects",',
        '#   "cost_centers"',
        "# GitHub repositories, the Jira sprint and team members are set there as well.",
    ]
    return "\n".join(lines).rstrip() + "\n"


def markdown() -> str:
    lines = [
        "# Connecting integrations",
        "",
        "<!-- Generated by `python -m scripts.connections --markdown`; do not edit by hand. -->",
        "",
        "Every integration is configured only through environment variables (`.env` locally, a",
        "Kubernetes Secret/ConfigMap in production). Fill in an integration's **required**",
        "variables, restart the API, and its tools appear for the agent. Nothing else changes.",
        "",
        "1. Run `python -m scripts.connections --init`: it creates `connections.env`, one file",
        "   with every platform below grouped by category, where to get each value and the docs.",
        "2. Paste the links and keys of the platforms you use (leave the others empty); keep",
        "   `DEMO_MODE=false` there. The file is git-ignored and overrides `.env`.",
        "3. Run `python -m scripts.connections` for a checklist of what is connected, then",
        "   `python -m scripts.connections --check` to test the live connections.",
        "",
        "Admins can see the same status in the API at `GET /api/v1/integrations?check=true`.",
        "",
    ]
    for category, title in CATEGORY_TITLES.items():
        specs = [s for s in ALL_SPECS if s.category == category]
        if not specs:
            continue
        lines += [f"## {title}", ""]
        for spec in specs:
            lines += [f"### {spec.title} (`{spec.name}`)", ""]
            if spec.setup:
                lines += [f"{spec.setup}.", ""]
            lines += [f"- Required: {', '.join(f'`{v.upper()}`' for v in spec.required)}"]
            if spec.optional:
                lines += [f"- Optional: {', '.join(f'`{v.upper()}`' for v in spec.optional)}"]
            if spec.docs_url:
                lines += [f"- API docs: {spec.docs_url}"]
            lines += [""]
    return "\n".join(lines).rstrip() + "\n"


def status_line(spec: ConnectorSpec, settings: Settings) -> str:
    missing = spec.missing(settings)
    if not missing:
        return f"  [x] {spec.title:<30} connected"
    started = len(missing) < len(spec.required)
    state = ("started, still missing " if started else "not set up: ") + ", ".join(missing)
    return f"  [{'~' if started else ' '}] {spec.title:<30} {state}"


async def check(settings: Settings) -> None:
    from backend.app.integrations.hub import build_integration_hub

    hub = build_integration_hub(settings)
    try:
        names = [s.name for s in ALL_SPECS if hub.enabled().get(s.name)]
        for result in await asyncio.gather(*(hub.check(n) for n in names)):
            mark = "ok  " if result.healthy else "FAIL"
            print(f"  [{mark}] {result.name:<16} {result.detail}")
        if not names:
            print("  nothing configured")
    finally:
        await hub.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="call each configured service")
    parser.add_argument(
        "--markdown",
        action="store_true",
        help="write docs/integrations.md and connections.env.example",
    )
    parser.add_argument("--init", action="store_true", help="create connections.env to fill in")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]

    if args.markdown:
        DOC.write_text(markdown(), encoding="utf-8")
        TEMPLATE.write_text(env_template(), encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)} and {TEMPLATE.relative_to(ROOT)}")
        return
    if args.init:
        if CONNECTIONS.exists():
            print(f"{CONNECTIONS.name} already exists; edit it (nothing was overwritten).")
        else:
            CONNECTIONS.write_text(env_template(), encoding="utf-8")
            print(
                f"created {CONNECTIONS.name}: paste your links and keys there, then run "
                "`python -m scripts.connections` to see what is connected."
            )
        return

    settings = Settings()
    source = CONNECTIONS.name if CONNECTIONS.exists() else ".env (run --init for connections.env)"
    print(f"Reading {source}")
    if settings.demo_mode:
        print("DEMO_MODE=true: every integration is served from synthetic data.")
    print()
    connected = 0
    for category, title in CATEGORY_TITLES.items():
        specs = [s for s in ALL_SPECS if s.category == category]
        if specs:
            print(title)
            for spec in specs:
                print(status_line(spec, settings))
                connected += not spec.missing(settings)
            print()
    print(f"{connected} of {len(ALL_SPECS)} platforms connected.")
    if args.check:
        print("\nConnectivity")
        asyncio.run(check(settings))


if __name__ == "__main__":
    main()
